import { CraftPiece, CraftPieceColor, CraftPieceType, CraftVariantConfig } from './craftGameTypes';

let pieceCounter = 1;
export function makePiece(type: CraftPieceType, color: CraftPieceColor): CraftPiece {
  return {
    id: `cp_${color}_${type}_${pieceCounter++}`,
    type,
    color,
    hasMoved: false,
  };
}

