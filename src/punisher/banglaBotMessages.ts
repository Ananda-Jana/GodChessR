/**
 * Retrieves a non-repeating Bengali message tailored to BanglaBot and situation.
 */
export function getRandomBanglaBotMessage(
  situation: BotMessageSituation,
  usedSet: Set<string>,
  context?: { piece?: string; square?: string }
): string {
  const pool = BANGLA_BOT_MESSAGES[situation] || [];
  const unusedPool = pool.filter((msg) => !usedSet.has(msg));

  let raw = "";
  if (unusedPool.length > 0) {
    raw = unusedPool[Math.floor(Math.random() * unusedPool.length)];
  } else {
    const genericPool = BANGLA_GENERIC_FALLBACK_MESSAGES[situation] || [];
    const unusedGeneric = genericPool.filter((msg) => !usedSet.has(msg));
    if (unusedGeneric.length > 0) {
      raw = unusedGeneric[Math.floor(Math.random() * unusedGeneric.length)];
    } else {
      const tauntPool = BANGLA_BOT_MESSAGES.midgameTaunt || [];
      const unusedTaunt = tauntPool.filter((msg) => !usedSet.has(msg));
      if (unusedTaunt.length > 0) {
        raw = unusedTaunt[Math.floor(Math.random() * unusedTaunt.length)];
      } else {
        raw = `তোর প্রতিটি চালের ওপর কড়া নজর রাখছি... (${usedSet.size + 1})`;
      }
    }
  }

  usedSet.add(raw);

  let formatted = raw;
  const banglaPiece = context?.piece ? (BANGLA_PIECE_NAMES[context.piece] || context.piece) : 'ঘুঁটি';
  formatted = formatted.replace(/{piece}/g, banglaPiece);
  formatted = formatted.replace(/{captured}/g, banglaPiece);

  if (context?.square) {
    formatted = formatted.replace(/{square}/g, context.square);
  } else {
    formatted = formatted.replace(/{square}/g, 'বোর্ডে');
  }

  return formatted;
}
